// Single source of truth for every Product Detail page in the catalog.
// Catalog facts (name/category/price/compareAt/rating/image/badge/slug)
// are transcribed unchanged from each page's own existing data (Men,
// Women, Equipment, Home). Narrative fields (description, tabs, features,
// reviewCount) did not exist anywhere in the project for any product
// except Summit Shell Jacket — those are newly authored, general,
// non-technical copy (see ProductDetailView for how they're consumed).
//
// Slug collisions: Men's and Women's catalogs independently use the same
// product names (e.g. "Ridge Softshell") for visually distinct items
// (different photo, sometimes a different badge). Women's colliding slugs
// are prefixed "womens-" so they never collide with Men's route; Men's
// slugs are left exactly as they already are on app/men/page.tsx. The one
// Equipment/Home name collision ("Timberline Trail Watch", two different
// prices/images) is resolved the same way: Equipment's copy becomes
// "equipment-timberline-trail-watch", Home's stays the bare
// "timberline-trail-watch" it already used.

// Shared price formatter — prices now carry cents (e.g. 249.99), and one
// requested value (Woodland Basecamp Kit, $299.00) is a whole number that
// still needs its trailing ".00" shown, which plain template-literal
// interpolation drops. Used everywhere a price/subtotal/total is rendered
// so every dollar amount on the site is displayed the same way.
export function formatPrice(amount: number): string {
  return amount.toFixed(2);
}

